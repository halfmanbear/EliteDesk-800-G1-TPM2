#!/usr/bin/env python3
"""Deterministically encode the tiny ASL companion; optionally cross-check with iasl.

This deliberately supports only this fixed SSDT, not arbitrary ASL compilation.
"""
import argparse
import pathlib
import struct
import subprocess
import tempfile

def package(opcode, body):
    for width in range(1, 5):
        total = len(body) + width
        if total < (1 << (6 if width == 1 else 4 + 8 * (width - 1))):
            if width == 1:
                length = bytes([total])
            else:
                length = bytes([((width - 1) << 6) | (total & 15)])
                length += bytes((total >> (4 + 8 * i)) & 255 for i in range(width - 1))
            return opcode + length + body
    raise ValueError("AML package too large")

def header(signature, revision, body):
    raw = bytearray(struct.pack("<4sIBB6s8sI4sI", signature, 36 + len(body),
                                revision, 0, b"ZENDI ", b"L01TPM2 ", 1, b"ZEND", 1) + body)
    raw[9] = -sum(raw) & 255
    return bytes(raw)

def tables():
    # Information byte bit0 = write status: 1 = read/write. The TPM TIS/FIFO
    # register window at 0xFED40000 is written by the OS driver (ACCESS, STS and
    # the command/response FIFO), so it must be ReadWrite, not ReadOnly.
    resources = b"\x86\x09\x00\x01" + struct.pack("<II", 0xFED40000, 0x5000) + b"\x79\x00"
    names = b"\x08_HID\x0dMSFT0101\x00\x08_UID\x0dL01-DIAG-TPM2\x00\x08_STA\x0a\x0f"
    names += b"\x08_CRS" + package(b"\x11", b"\x0a" + bytes([len(resources)]) + resources)
    # Method (_DSM, 4, NotSerialized) { Return (Buffer (One) { 0x00 }) }
    # Windows tpm.sys evaluates _DSM (physical presence / MOR). A missing method makes
    # acpi.sys fail the request with STATUS_OBJECT_NAME_NOT_FOUND (0xC0000034), which
    # tpm.sys logs as TPM event 15 and Get-Tpm reports as 0x80284001 (hardware: first-windows-tpm-detection, docs/HISTORY.md).
    # An empty function bitmap means "no _DSM functions supported": no PPI, no MOR.
    dsm = package(b"\x14", b"_DSM\x04" + b"\xa4" + package(b"\x11", b"\x01\x00"))  # BufferSize One, data 0x00
    assert dsm == bytes.fromhex("140b5f44534d04a41103 0100".replace(" ", "")), dsm.hex()
    device = package(b"\x5b\x82", b"ZTP2" + names + dsm)
    ssdt = header(b"SSDT", 2, package(b"\x10", b"\\_SB_" + device))
    tpm2 = header(b"TPM2", 3, struct.pack("<IQI", 0, 0, 6))
    assert len(tpm2) == 52 and sum(tpm2) % 256 == sum(ssdt) % 256 == 0
    assert b"MSFT0101\x00" in ssdt and b"\x86\x09\x00\x01\x00\x00\xd4\xfe\x00\x50\x00\x00\x79\x00" in ssdt
    return ssdt, tpm2

def write_header(path):
    """Write the generated tables as a C header; returns (ssdt, tpm2)."""
    ssdt, tpm2 = tables()
    out = ["/* Generated by scripts/generate_tpm2_acpi.py. */", "#ifndef TPM2_TABLES_H", "#define TPM2_TABLES_H"]
    for name, value in (("diag_ssdt", ssdt), ("diag_tpm2", tpm2)):
        out.append(f"static const unsigned char {name}[] = {{")
        out.extend("    " + ", ".join(f"0x{x:02x}" for x in value[i:i+12]) + "," for i in range(0, len(value), 12))
        out.append("};")
    out.append("#endif\n")
    path = pathlib.Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(out))
    return ssdt, tpm2

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=pathlib.Path, required=True, help="Header to write (e.g. a scratch folder)")
    parser.add_argument("--iasl", help="Optional path to ACPICA iasl; validate generated AML by disassembly")
    args = parser.parse_args()
    ssdt, tpm2 = tables()
    if args.iasl:
        with tempfile.TemporaryDirectory() as temp:
            prefix = pathlib.Path(temp) / "tpm2"
            aml = prefix.with_suffix(".aml")
            aml.write_bytes(ssdt)
            subprocess.run([args.iasl, "-p", str(prefix), "-d", str(aml)], check=True)
            subprocess.run([args.iasl, "-p", str(prefix), str(prefix.with_suffix(".dsl"))], check=True)
            # ACPI compiler identity changes are expected; AML payload must round-trip.
            assert aml.read_bytes()[36:] == ssdt[36:], "iasl round-trip changed AML"
    write_header(args.output)
    print(f"SSDT {len(ssdt)} bytes, TPM2 {len(tpm2)} bytes -> {args.output}")

if __name__ == "__main__":
    main()
